#!/usr/bin/env bash
# Populate an archiso airootfs overlay. The compositor reads the writable
# per-user scene tree created from /etc/skel, just like an upstream install.
set -euo pipefail
umask 022
root=$(realpath -e "${1:?usage: stage-desktop.sh AIROOTFS}")
[[ -d "$root" && "$root" != / ]] || exit 2
project=$(cd -- "$(dirname -- "$0")/.." && pwd)
assets=$project/desktop
skel=$root/etc/skel
dest=$skel/.config/pleamar/shells/vitreus
local_bin=$skel/.local/bin
data=$skel/.local/share/pleamar/vitreus

mkdir -p "$dest" "$local_bin" "$data" "$skel/.config/hypr" "$skel/.config/ghostty"
# Reference photographs and video demos stay in the repository's README.
tar --exclude='./assets/screenshots' --exclude='./.git' -C "$assets/vitreus" -cf - . | tar -C "$dest" -xf -
# The theme catalog is generated by the upstream scanner from the .toml files.
rm -f "$dest/themes/uwu.toml"
cp "$dest/palette.default.plm" "$dest/palette.plm"
cp "$dest/wm-palette.default.plm" "$dest/wm-palette.plm"
for helper in "$dest"/bin/*; do
    if [[ -f "$helper" && -x "$helper" ]]; then
        ln -sfn "../../.config/pleamar/shells/vitreus/bin/${helper##*/}" "$local_bin/${helper##*/}"
    fi
done

install -m 644 "$assets/session/hyprland.lua" "$skel/.config/hypr/hyprland.lua"
ln -sfn ../pleamar/shells/vitreus/hypr_vitreus.lua "$skel/.config/hypr/hypr_vitreus.lua"
ln -sfn ../pleamar/shells/vitreus/pleamar-wm/hypridle.conf "$skel/.config/hypr/hypridle.conf"
install -m 644 "$assets/session/autostart" "$skel/.config/pleamar/autostart"
# The left Frame is the native Vitreus preset shown in the README's dashboard.
printf '%s\n' '{"pos":"left","left":true}' > "$data/bar-position.json"
install -Dm755 "$assets/session/wayland-session" "$root/usr/local/lib/vitreus-iso/wayland-session"
install -Dm755 "$assets/session/wallpaper" "$root/usr/local/lib/vitreus-iso/wallpaper"
install -Dm644 "$dest/assets/greeter.jpeg" "$skel/Pictures/Wallpapers/Vitreus.jpeg"

mkdir -p "$skel/.local/share/fonts"
cp -R "$assets/fonts/." "$skel/.local/share/fonts/"
printf '%s\n' 'config-file = ?~/.config/pleamar/shells/vitreus/terminal/ghostty.conf' > "$skel/.config/ghostty/config"
if [[ ! -f "$skel/.bashrc" ]]; then
    install -m 644 /etc/skel/.bashrc "$skel/.bashrc"
fi
if ! grep -q '# vitreus: vitfetch' "$skel/.bashrc" 2>/dev/null; then
    cat >>"$skel/.bashrc" <<'RC'
case "$TERM" in xterm-ghostty|xterm-kitty) "$HOME/.local/bin/vitfetch" ;; esac  # vitreus: vitfetch
RC
fi

for program in files view; do
    install -Dm755 "$assets/session/desktop-helper" "$root/usr/local/bin/vitreus-$program"
    install -Dm644 "$dest/$program/vitreus-$program.svg" "$root/usr/share/icons/hicolor/scalable/apps/vitreus-$program.svg"
    mkdir -p "$root/usr/share/applications"
    sed "s|@BIN@|/usr/local/bin/vitreus-$program|g" "$dest/$program/vitreus-$program.desktop" >"$root/usr/share/applications/vitreus-$program.desktop"
done
install -Dm755 "$assets/session/desktop-helper" "$root/usr/local/bin/vitreus-filemanager"
mkdir -p "$root/usr/share/dbus-1/services"
cat >"$root/usr/share/dbus-1/services/org.freedesktop.FileManager1.service" <<'DBUS'
[D-BUS Service]
Name=org.freedesktop.FileManager1
Exec=/usr/local/bin/vitreus-filemanager
DBUS
{
    echo '[Default Applications]'
    echo 'inode/directory=vitreus-files.desktop'
    sed -n 's/^MimeType=//p' "$dest/view/vitreus-view.desktop" | tr ';' '\n' | sed '/^$/d;s/$/=vitreus-view.desktop/'
} > "$skel/.config/mimeapps.list"

tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT
protocol=$(pkg-config --variable=pkgdatadir wayland-protocols)/unstable/idle-inhibit/idle-inhibit-unstable-v1.xml
wayland-scanner client-header "$protocol" "$tmp/idle-inhibit.h"
wayland-scanner private-code "$protocol" "$tmp/idle-inhibit.c"
cc -O2 -I"$tmp" -o "$local_bin/vitreus-inhibit" "$dest/bin/vitreus-inhibit.c" "$tmp/idle-inhibit.c" $(pkg-config --cflags --libs wayland-client)

# The greeter's upstream generator extracts the original font's three weights.
# Use the staged user's fontconfig search path so it finds Space Grotesk.
(
    export HOME="$skel" XDG_DATA_HOME="$skel/.local/share" XDG_CACHE_HOME="$tmp/cache"
    unset XDG_CONFIG_HOME FONTCONFIG_FILE
    [[ $(fc-match -f '%{family}' 'Space Grotesk') == *'Space Grotesk'* ]]
    python3 -c 'import fontTools.varLib.instancer'
    "$dest/sddm/build-assets.sh" "$root/usr/share/sddm/themes/vitreus"
)
install -Dm644 "$assets/fonts/SpaceGrotesk/OFL.txt" "$root/usr/share/sddm/themes/vitreus/fonts/OFL.txt"
mkdir -p "$root/etc/sddm.conf.d" "$root/usr/lib/tmpfiles.d"
printf '[Theme]\nCurrent=vitreus\n' > "$root/etc/sddm.conf.d/10-vitreus-theme.conf"
printf 'd /usr/local/share/vitreus-greeter 0755 vitreus vitreus -\n' > "$root/usr/lib/tmpfiles.d/vitreus-greeter.conf"
